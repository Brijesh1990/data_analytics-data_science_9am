# w.a.p to print additions | substractions and multiplications 
# inp=1 = additions
# inp=2 = substractions 
# inp=3 = multiplications
inp=int(input("Enter input to be performed :"))
if inp==1:
    a=10
    b=20
    c=a+b
    print("Additions of numbers is :",c)
    
if inp==2:
    a=10
    b=20
    c=a-b
    print("Substractions of numbers is :",c)
    
    
if inp==3:
    a=10
    b=20
    c=a*b
    print("Multiplications of numbers is :",c)